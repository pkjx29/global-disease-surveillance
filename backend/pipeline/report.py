"""Evaluation report: how much data, which weeks, and how well the models do on them.

``python -m pipeline report`` trains exactly as ``python -m pipeline train`` does but writes
nothing to the database. It saves ``docs/model/model_report.json`` (everything) and
``docs/model/model_report.md`` (the tables a reader needs), including the dataset hash,
split dates and library versions, so a result can be traced to its inputs.
"""

from __future__ import annotations

import hashlib
import json
import logging
import platform
import subprocess
from datetime import UTC, datetime
from importlib.metadata import version
from pathlib import Path

import pandas as pd

from . import load
from .features import build_panel
from .model import PARAMS, evaluate, read_inputs
from .settings import BACKEND_ROOT, HORIZON_WEEKS

log = logging.getLogger(__name__)

OUT_DIR = BACKEND_ROOT.parent / "docs" / "model"
REQUESTED_TEST_WINDOW = ("2023-01-01", "2026-08-31")      # anchor weeks the project brief asks about


def dataset_hash(cases: pd.DataFrame) -> str:
    """SHA-256 of the case table in a fixed order: same hash = same input data."""
    ordered = cases.sort_values(["disease", "iso3", "week_start"]).reset_index(drop=True)
    return hashlib.sha256(ordered.to_csv(index=False).encode()).hexdigest()


def coverage(cases: pd.DataFrame, panel: pd.DataFrame, test: pd.DataFrame) -> dict:
    """Row counts at each stage, per disease, and whether the requested test window is covered."""
    stages = {}
    for disease, rows in cases.groupby("disease"):
        p = panel[panel["disease"] == disease]
        stages[disease] = {
            "case_report_rows": int(len(rows)),
            "reported_weeks": int(rows["reported"].sum()),
            "unreported_weeks": int((~rows["reported"]).sum()),
            "countries": int(rows["iso3"].nunique()),
            "first_week": str(pd.Timestamp(rows["week_start"].min()).date()),
            "last_week": str(pd.Timestamp(rows["week_start"].max()).date()),
            "panel_rows": int(len(p)),
            "feature_valid": int(p["feature_valid"].sum()),
            "label_valid": int(p["label_valid"].sum()),
        }
    start, end = (pd.Timestamp(d) for d in REQUESTED_TEST_WINDOW)
    in_window = panel[(panel["week_start"] >= start) & (panel["week_start"] <= end) & panel["feature_valid"]]
    last_anchor = test["week_start"].max()
    return {
        "country_week_definition": "one disease, one country, one ISO week starting Monday (a 'country-disease-week')",
        "case_report_rows": int(len(cases)),
        "by_disease": stages,
        "requested_test_window": list(REQUESTED_TEST_WINDOW),
        "test_anchor_range": [str(test["week_start"].min().date()), str(last_anchor.date())],
        "label_follow_up_until": str((last_anchor + pd.Timedelta(weeks=HORIZON_WEEKS, days=6)).date()),
        "anchors_in_window_with_features": int(len(in_window)),
        "anchors_in_window_evaluated": int(in_window["label_valid"].sum()),
        "anchors_in_window_excluded": int((~in_window["label_valid"]).sum()),
        "exclusion_reason": f"fewer than {HORIZON_WEEKS} reported weeks of follow-up (end of data or reporting gaps); never labelled negative",
    }


def environment() -> dict:
    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True, cwd=BACKEND_ROOT).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = None
    return {
        "created_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "git_commit": commit,
        "python": platform.python_version(),
        "platform": platform.platform(),
        "packages": {p: version(p) for p in ("xgboost", "scikit-learn", "pandas", "numpy")},
    }


def fmt(value, digits: int = 3) -> str:
    return "undefined" if value is None else f"{value:.{digits}f}"


def markdown(report: dict) -> str:
    m, cov = report["metrics"], report["coverage"]
    lines = [
        "# Outbreak-risk model: evaluation report",
        "",
        f"Generated by `python -m pipeline report` at {report['environment']['created_at']} (commit {report['environment']['git_commit']}, "
        f"xgboost {report['environment']['packages']['xgboost']}, {report['environment']['platform']}).",
        f"Dataset hash `{report['dataset_sha256'][:16]}…`. Experimental estimates, not public-health guidance.",
        "",
        f"**Label.** {m['definition']}.",
        f"**Split.** Train anchors up to {m['train_end']} minus {HORIZON_WEEKS} weeks; validation (early stopping and threshold) "
        f"{m['validation_period'][0]} to {m['validation_period'][1]}; test anchors {m['test_period'][0]} to {m['test_period'][1]}, "
        f"with outcomes followed up to {cov['label_follow_up_until']}.",
        "",
        "## Held-out performance",
        "",
        "| Model | ROC-AUC | PR-AUC | Brier | Threshold (from validation) | Precision | Recall | Specificity | F1 | Balanced accuracy |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    rows = (("XGBoost", "xgboost", "xgboost_at_threshold"), ("Logistic regression", "baseline_logistic_regression", "logistic_regression_at_threshold"))
    for name, ranking, at in rows:
        r, t = m[ranking], m[at]
        lines.append(
            f"| {name} | {fmt(r['roc_auc'])} | {fmt(r['pr_auc'])} | {fmt(r.get('brier'))} | {t['threshold']:.3f} | {fmt(t['precision'])} | "
            f"{fmt(t['recall'])} | {fmt(t['specificity'])} | {fmt(t['f1'])} | {fmt(t['balanced_accuracy'])} |"
        )
    p = m["baseline_persistence"]
    lines += [
        f"| Growth-rate rule | {fmt(p['roc_auc'])} | {fmt(p['pr_auc'])} | – | – | – | – | – | – | – |",
        "",
        f"Test rows {m['test_rows']:,}, outbreaks {m['xgboost']['positives']:,} (prevalence {m['xgboost']['prevalence']:.3f}).",
        "",
    ]
    for name, at in (("XGBoost", "xgboost_at_threshold"), ("Logistic regression", "logistic_regression_at_threshold")):
        t = m[at]
        lines.append(f"{name} confusion matrix at {t['threshold']:.3f}: TP {t['tp']:,}, FP {t['fp']:,}, FN {t['fn']:,}, TN {t['tn']:,}.  ")
    lines += ["", "## By disease (XGBoost)", "", "| Disease | Rows | Outbreaks | ROC-AUC | PR-AUC |", "|---|---|---|---|---|"]
    for disease, r in m["by_disease"].items():
        lines.append(f"| {disease} | {r['n']:,} | {r['positives']:,} | {fmt(r.get('roc_auc'))} | {fmt(r.get('pr_auc'))} |")
    lines += ["", "## Rolling origin (re-train before each year)", ""]
    lines += ["| Test year | Train rows | Rows | Outbreaks | ROC-AUC | PR-AUC |", "|---|---|---|---|---|---|"]
    for f in m["rolling_origin"]:
        lines.append(f"| {f['test_year']} | {f['train_rows']:,} | {f['n']:,} | {f['positives']:,} | {fmt(f['roc_auc'])} | {fmt(f['pr_auc'])} |")
    lines += [
        "",
        "## Data coverage",
        "",
        f"One row = {cov['country_week_definition']}. `case_reports` holds {cov['case_report_rows']:,} rows.",
        "",
        "| Disease | Rows | Reported weeks | Unreported weeks | Countries | First week | Last week | With features | Labelled |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for disease, s in cov["by_disease"].items():
        lines.append(
            f"| {disease} | {s['case_report_rows']:,} | {s['reported_weeks']:,} | {s['unreported_weeks']:,} | {s['countries']} | "
            f"{s['first_week']} | {s['last_week']} | {s['feature_valid']:,} | {s['label_valid']:,} |"
        )
    lines += [
        "",
        f"Requested test window {cov['requested_test_window'][0]} to {cov['requested_test_window'][1]}: "
        f"{cov['anchors_in_window_with_features']:,} anchor rows have features, {cov['anchors_in_window_evaluated']:,} are evaluated and "
        f"{cov['anchors_in_window_excluded']:,} are excluded ({cov['exclusion_reason']}). The last evaluated anchor is "
        f"{cov['test_anchor_range'][1]}; later August 2026 anchors have no complete four-week outcome yet.",
        "",
    ]
    return "\n".join(lines)


def run(engine=None, out_dir: Path = OUT_DIR) -> dict:
    engine = engine or load.get_engine()
    cases, countries, neighbours = read_inputs(engine)
    panel = build_panel(cases, countries, neighbours)
    model, _, test, metrics = evaluate(panel)
    report = {
        "dataset_sha256": dataset_hash(cases),
        "environment": environment(),
        "params": PARAMS | {"best_iteration": int(model.best_iteration)},
        "metrics": metrics,
        "coverage": coverage(cases, panel, test),
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "model_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    (out_dir / "model_report.md").write_text(markdown(report), encoding="utf-8")
    log.info("report written to %s", out_dir)
    return report
