"""Source catalogue: what each public dataset is, the exact file used and what it contributed.

``python -m pipeline manifest`` reads the raw-file sidecars written at download time and
counts, in the database, the rows each source actually contributed. It writes
``docs/data/sources.json`` and ``docs/data/sources.md``.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

from sqlalchemy import text

from . import load, sources
from .settings import BACKEND_ROOT

log = logging.getLogger(__name__)

OUT_DIR = BACKEND_ROOT.parent / "docs" / "data"

# what each source covers and how it is used (checked against the files and transform.py)
CONTENT = {
    "covid19": ("COVID-19 cases and deaths", "weekly, national", "case_reports (disease = covid19)"),
    "mpox": ("mpox cases and deaths", "daily, national; summed to ISO weeks", "case_reports (disease = mpox)"),
    "dengue": ("dengue cases", "weekly or coarser, national; only weekly rows used", "case_reports (disease = dengue)"),
    "cholera_cases": ("cholera cases", "annual, national", "annual_indicators (cholera_cases); not used by the model"),
    "measles_cases": ("measles cases", "annual, national", "annual_indicators (measles_cases); not used by the model"),
    "countries": ("country boundaries and population", "static", "countries, country_neighbours"),
}

CONTRIBUTION_SQL = {
    "covid19": "SELECT count(*), count(*) FILTER (WHERE reported) FROM case_reports WHERE disease = 'covid19'",
    "mpox": "SELECT count(*), count(*) FILTER (WHERE reported) FROM case_reports WHERE disease = 'mpox'",
    "dengue": "SELECT count(*), count(*) FILTER (WHERE reported) FROM case_reports WHERE disease = 'dengue'",
    "cholera_cases": "SELECT count(*), count(*) FROM annual_indicators WHERE indicator = 'cholera_cases'",
    "measles_cases": "SELECT count(*), count(*) FROM annual_indicators WHERE indicator = 'measles_cases'",
    "countries": "SELECT count(*), count(*) FILTER (WHERE has_geometry) FROM countries",
}


def run(engine=None, out_dir: Path = OUT_DIR) -> list[dict]:
    engine = engine or load.get_engine()
    catalogue = []
    with engine.connect() as conn:
        for key, src in sources.SOURCES.items():
            meta_file = sources.meta_path(key)
            meta = json.loads(meta_file.read_text(encoding="utf-8")) if meta_file.exists() else None
            rows, valid = conn.execute(text(CONTRIBUTION_SQL[key])).one()
            content, resolution, used_in = CONTENT[key]
            catalogue.append(
                {
                    "key": key,
                    "provider": src.provider,
                    "url": src.url,
                    "licence": src.licence,
                    "content": content,
                    "resolution": resolution,
                    "used_in": used_in,
                    "rows_in_database": int(rows),
                    "rows_reported_or_with_geometry": int(valid),
                    "file": meta,                   # None: raw file not present on this machine
                }
            )
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "sources.json").write_text(json.dumps(catalogue, indent=2), encoding="utf-8")
    lines = [
        "# Data sources",
        "",
        "Generated by `python -m pipeline manifest`. Row counts are what each source contributed to the database.",
        "`sha256` and the retrieval time describe the copy now in `backend/data/raw`. They describe the database contents only",
        "if the ETL was last run on that copy; sources such as the WHO file are revised over time.",
        "",
        "| Source | Content | Resolution | Used in | Rows | Reported / with geometry | Licence | Retrieved | SHA-256 |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for c in catalogue:
        f = c["file"] or {}
        lines.append(
            f"| [{c['provider']}]({c['url']}) | {c['content']} | {c['resolution']} | {c['used_in']} | {c['rows_in_database']:,} | "
            f"{c['rows_reported_or_with_geometry']:,} | {c['licence']} | {f.get('retrieved_at', 'not recorded')} | `{f.get('sha256', 'n/a')[:12]}` |"
        )
    (out_dir / "sources.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info("source catalogue written to %s", out_dir)
    return catalogue
